"""Interim-report build of the v3 plain-academic rewrite (T53, CCDS interim deadline).

Same contract as ``scripts/build_rewritten_fyp_interim_v1.py`` (which documents the
rationale): the CCDS interim submission (Mon 24 Aug 2026) and the final submission
(Mon 19 Oct 2026) carry the same body, and only the document's self-description
differs. This builder runs ``scripts/build_rewritten_fyp_report_v3.py`` unchanged
and then rewrites the three places where the artefact names itself:

  * the cover line          "Final Year Project Report" -> "Interim Report"
  * the front-matter header "CCDS25-1136 - Final ..."   -> "CCDS25-1136 - Interim Report"
  * the docx core properties

Keeping one source of prose is deliberate. Duplicating a 160 KB builder is how v5
came to carry 19 claim-to-source defects that were only ever fixed in v6 (D56): two
copies drift, and a correction applied to one is silently absent from the other.
Here a change to the v3 rewrite reaches the interim on the next build, by
construction.

The report builder is imported, not modified, and writes to its own path first so
that ``docs/rewritten_fyp_report_v3.docx`` is left byte-identical to a normal build.

    python scripts/build_rewritten_fyp_interim_v3.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

from docx import Document

ROOT = Path(__file__).resolve().parents[1]
REPORT_BUILDER = ROOT / "scripts" / "build_rewritten_fyp_report_v3.py"
OUT = ROOT / "docs" / "rewritten_fyp_interim_v3.docx"

# The exact strings the document uses to name itself. Each must be found; a silent
# miss would ship an interim submission still calling itself the final report.
COVER_LINE = ("Final Year Project Report", "Interim Report")
RUNNING_HEADER = (
    "CCDS25-1136 · Final Year Project Report",
    "CCDS25-1136 · Interim Report",
)


def load_report_builder():
    spec = importlib.util.spec_from_file_location("build_rewritten_fyp_report_v3_for_interim", REPORT_BUILDER)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def retitle(doc: Document) -> dict[str, int]:
    """Replace the self-naming strings in body runs and in every section header."""
    counts = {COVER_LINE[0]: 0, RUNNING_HEADER[0]: 0}

    for paragraph in doc.paragraphs:
        for run in paragraph.runs:
            if run.text.strip() == COVER_LINE[0]:
                run.text = run.text.replace(COVER_LINE[0], COVER_LINE[1])
                counts[COVER_LINE[0]] += 1

    for section in doc.sections:
        for header in (section.header, section.first_page_header, section.even_page_header):
            if header is None:
                continue
            for paragraph in header.paragraphs:
                for run in paragraph.runs:
                    if RUNNING_HEADER[0] in run.text:
                        run.text = run.text.replace(*RUNNING_HEADER)
                        counts[RUNNING_HEADER[0]] += 1
    return counts


def build_interim() -> Path:
    module = load_report_builder()
    report_path = module.build_report()  # writes the report to its own path, untouched

    doc = Document(str(report_path))
    counts = retitle(doc)

    if counts[COVER_LINE[0]] != 1:
        raise SystemExit(
            f"expected exactly one cover line {COVER_LINE[0]!r}, found {counts[COVER_LINE[0]]}. "
            "The report cover changed; update COVER_LINE before shipping an interim."
        )
    if counts[RUNNING_HEADER[0]] < 1:
        raise SystemExit(
            f"running header {RUNNING_HEADER[0]!r} was not found. "
            "The report header changed; update RUNNING_HEADER before shipping an interim."
        )

    doc.core_properties.title = "Benchmarking Ethical Performance of Open-Source LLMs"
    doc.core_properties.subject = "Interim report (CCDS interim submission)"
    doc.core_properties.author = "TAN UEI HORNG"
    doc.core_properties.comments = (
        "Interim-submission build. Body is identical to the v3 plain-academic rewrite; only the "
        "document's self-description differs. Generated by scripts/build_rewritten_fyp_interim_v3.py."
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    return OUT


if __name__ == "__main__":
    print(build_interim())
