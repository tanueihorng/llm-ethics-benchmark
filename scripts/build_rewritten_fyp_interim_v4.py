#!/usr/bin/env python3
"""Build the v4 interim copy from the v4 report builder.

The body is generated by ``build_rewritten_fyp_report_v4.py`` and only the
document self-description is retitled for the interim submission.  v3 remains
unchanged as a comparison artefact.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

from docx import Document


ROOT = Path(__file__).resolve().parents[1]
REPORT_BUILDER = ROOT / "scripts" / "build_rewritten_fyp_report_v4.py"
OUT = ROOT / "docs" / "rewritten_fyp_interim_v4.docx"

COVER_LINE = ("Final Year Project Report", "Interim Report")
RUNNING_HEADER = (
    "CCDS25-1136 · Final Year Project Report",
    "CCDS25-1136 · Interim Report",
)


def load_report_builder():
    spec = importlib.util.spec_from_file_location("build_rewritten_fyp_report_v4_for_interim", REPORT_BUILDER)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import {REPORT_BUILDER}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def retitle(doc: Document) -> dict[str, int]:
    counts = {COVER_LINE[0]: 0, RUNNING_HEADER[0]: 0}
    for paragraph in doc.paragraphs:
        for run in paragraph.runs:
            if COVER_LINE[0] in run.text:
                run.text = run.text.replace(*COVER_LINE)
                counts[COVER_LINE[0]] += 1
    for section in doc.sections:
        for header in (section.header, section.first_page_header, section.even_page_header):
            if header is None:
                continue
            for paragraph in header.paragraphs:
                for run in paragraph.runs:
                    if RUNNING_HEADER[0] in run.text:
                        run.text = run.text.replace(*RUNNING_HEADER)
                        counts[RUNNING_HEADER[0]] += 1
    return counts


def build_interim() -> Path:
    module = load_report_builder()
    report_path = module.build_report()
    doc = Document(str(report_path))
    counts = retitle(doc)
    if counts[COVER_LINE[0]] != 1:
        raise SystemExit(f"expected one cover line, found {counts[COVER_LINE[0]]}")
    if counts[RUNNING_HEADER[0]] < 1:
        raise SystemExit(f"running header was not found: {RUNNING_HEADER[0]!r}")

    doc.core_properties.title = "Benchmarking Ethical Performance of Open-Source LLMs"
    doc.core_properties.subject = "Interim report (CCDS interim submission), v4 funnel introduction"
    doc.core_properties.author = "TAN UEI HORNG"
    doc.core_properties.comments = (
        "Interim v4 build. Body is generated by the v4 report builder; only the self-description is retitled."
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    return OUT


if __name__ == "__main__":
    print(build_interim())
